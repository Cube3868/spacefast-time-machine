async (page) => {
  const base=new URL(page.url()).origin
  const check=(v,m)=>{if(!v)throw Error(m)}
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(base+'/')
  check(await page.locator('meta[property="og:image"]').getAttribute('content')==='https://space-xx8uckgsp.space.fast/social-card.png?v=launch-2','Launch image metadata must identify the new card')
  check(await page.locator('meta[name="twitter:image"]').getAttribute('content')===await page.locator('meta[property="og:image"]').getAttribute('content'),'Chat and Twitter cards must agree')
  check(await page.locator('.source-link').getAttribute('href')==='https://github.com/Cube3868/spacefast-time-machine','App source link must open the actual GitHub repo')
  const card=await page.request.get(base+'/social-card.png?v=launch-2')
  check(card.status()===200 && card.headers()['content-type'].includes('image/png'),'Public card must serve as PNG')
  await page.goto(base+(base.includes('127.0.0.1')?'/walkthrough/index.html':'/walkthrough/'))
  await page.getByRole('heading',{name:'Every version. Within reach.',exact:true}).waitFor()
  await page.waitForFunction(()=>document.querySelector('video').readyState>=2)
  const video=await page.locator('video').evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,error:v.error?.code,tracks:v.textTracks.length}))
  check(video.duration>39 && video.duration<40 && video.width===1920 && video.height===1080 && !video.error,'Real 1080p walkthrough must load')
  await page.locator('video').evaluate(v=>{v.muted=true;return v.play()})
  await page.waitForFunction(()=>document.querySelector('video').currentTime>1)
  const audioTracks=await page.locator('video').evaluate(v=>v.captureStream().getAudioTracks().length)
  check(audioTracks===1,'Walkthrough must include the requested sound-effects track')
  await page.locator('video').evaluate(v=>{v.pause();v.currentTime=27})
  await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-27)<.2 && !document.querySelector('video').seeking)
  check((await page.locator('video').evaluate(v=>v.error))===null,'Video must play and seek without an error')
  const captions=await page.request.get(base+'/walkthrough/walkthrough.vtt')
  check(captions.status()===200 && (await captions.text()).startsWith('WEBVTT'),'Accessible captions must be available')
  await page.locator('video').evaluate(v=>{v.textTracks[0].mode='hidden'})
  await page.waitForFunction(()=>document.querySelector('track').readyState===2)
  check(await page.locator('video').evaluate(v=>v.textTracks[0].cues.length)===9,'Browser must parse all nine caption cues')
  check(await page.getByRole('link',{name:'Download walkthrough',exact:false}).getAttribute('download')!==null,'MP4 download must be exposed')
  await page.getByText('Read the walkthrough transcript',{exact:true}).click()
  check(await page.locator('details').getAttribute('open')!==null,'Transcript must open with native controls')
  const audit=async()=>{
    await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'})
    const violations=await page.evaluate(async()=> (await axe.run(document,{runOnly:['wcag2a','wcag2aa','wcag21aa']})).violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})))
    check(!violations.length,'Walkthrough accessibility: '+JSON.stringify(violations))
  }
  await audit()
  await page.locator('video').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/launch-walkthrough-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Walkthrough must fit mobile')
  await audit()
  await page.screenshot({path:'artifacts/launch-walkthrough-mobile.png',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  return {base,video,audioTracks,checks:'PNG social metadata, actual GitHub link, video load/play/seek, sound track, captions, download, transcript, responsive layout, zero automated WCAG AA violations on desktop and mobile'}
}
