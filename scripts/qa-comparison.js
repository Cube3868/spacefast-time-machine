async (page) => {
  const base = new URL(page.url()).origin
  const check = (v,m) => {if(!v) throw new Error(m)}
  const results=[]
  const audit=async(name)=>{await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});const violations=await page.evaluate(async()=> (await axe.run(document,{runOnly:['wcag2a','wcag2aa','wcag21aa']})).violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})));check(!violations.length,name+': '+JSON.stringify(violations));results.push(name+': zero automated WCAG AA violations')}
  const q=new URLSearchParams({demo:'1',space:'spc_ee81cba49aa7483181d752847a250bf9',version:'ver_ed7fee22bb1842d3badda9f627fbfffe',compare:'ver_095054a0c3ea489e81706f8c603f4cbb',view:'files'})
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(base+'/?'+q)
  await page.locator('.diff-table tr.added').first().waitFor()
  check(await page.getByRole('tab',{name:'Files',exact:true}).getAttribute('aria-selected') === 'true','Deep link must open Files view')
  check(await page.locator('.file-text script').count() === 0,'Served HTML must be escaped, never executed')
  check((await page.locator('.diff-table').innerText()).includes('Good things'),'Diff must contain real release content')
  await audit('Deployment file diff')
  await page.getByRole('button',{name:'Before / after',exact:true}).click()
  await page.getByRole('heading',{name:'Before · v2',exact:true}).waitFor()
  check((await page.locator('.text-side').first().innerText()).includes('A little more space'),'Before text must be v2')
  check((await page.locator('.text-side').last().innerText()).includes('Good things'),'After text must be v1')
  await page.getByRole('button',{name:'Unified diff',exact:true}).click()
  await page.getByRole('button',{name:'Share comparison',exact:true}).click()
  const value=await page.getByRole('textbox',{name:'Comparison link',exact:true}).inputValue()
  const shared=new URL(value)
  check(shared.searchParams.get('version')===q.get('version') && shared.searchParams.get('compare')===q.get('compare') && shared.searchParams.get('view')==='files','Shared URL must preserve exact pair and view')
  check([...shared.searchParams.keys()].every(k=>['demo','space','version','compare','view'].includes(k)),'Share links contain navigation only')
  await page.evaluate(()=>{window.__qaComparisonCopied='';Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.__qaComparisonCopied=text}}})})
  await page.getByRole('button',{name:'Copy comparison link',exact:true}).click()
  await page.getByText('Link copied to your clipboard.',{exact:true}).waitFor()
  check(await page.evaluate(()=>window.__qaComparisonCopied)===value,'Copy button must copy exact comparison URL')
  await audit('Share comparison dialog')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Restore activity',exact:true}).click()
  await page.getByRole('heading',{name:'The shared demo never changes a live site',exact:true}).waitFor()
  check(await page.locator('.activity-list li').count()===0,'Public demo must never invent restore records')
  await audit('Demo restore activity')
  await page.keyboard.press('Escape')
  await page.reload()
  await page.locator('.diff-table tr.added').first().waitFor()
  check(new URL(page.url()).searchParams.get('version')===q.get('version'),'Exact comparison must survive reload')
  await page.locator('.changes-view').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/file-diff-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(()=>document.getElementById('sidebar').getBoundingClientRect().right<=0)
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'File diff must fit mobile without page overflow')
  await audit('Mobile file diff')
  await page.locator('.changes-view').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/file-diff-mobile.png',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  return [...results,'Real API-snapshot text diff, before/after view, escaped HTML, exact shared URLs, clipboard handler, reload and mobile layout passed']
}
