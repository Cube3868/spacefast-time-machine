async (page) => {
  // No mocked provider calls, account cookies read, or security policies disabled.
  const base = "https://space-xx8uckgsp.space.fast"
  const check = (value, message) => { if (!value) throw new Error(message) }
  const root = await page.request.get(base)
  check(root.status() === 200, "Public app must return 200")
  const headers = root.headers()
  check(headers["content-security-policy"]?.includes("frame-ancestors 'none'"), "Deployed app must retain its framing policy")
  check(headers["x-content-type-options"] === "nosniff", "Deployed app must retain nosniff")
  const health = await (await page.request.get(base + "/api/health")).json()
  check(health.database === true, "Live Functions database query must pass")
  await page.setViewportSize({width:1440,height:1000})
  const fileLink = base + '/?demo=1&space=spc_ee81cba49aa7483181d752847a250bf9&version=ver_095054a0c3ea489e81706f8c603f4cbb&compare=ver_ed7fee22bb1842d3badda9f627fbfffe&view=files'
  await page.goto(fileLink)
  await page.locator('.diff-table tr.added').first().waitFor()
  check(await page.getByRole('tab',{name:'Files',exact:true}).getAttribute('aria-selected')==='true','Production deep link must open Files')
  check(await page.locator('.file-text script').count()===0,'Production file text must never execute markup')
  await page.getByRole('button',{name:'Share comparison',exact:true}).click()
  const shared=new URL(await page.getByRole('textbox',{name:'Comparison link',exact:true}).inputValue())
  check(shared.searchParams.get('version')==='ver_095054a0c3ea489e81706f8c603f4cbb' && shared.searchParams.get('view')==='files','Production share link must preserve pair and view')
  await page.keyboard.press('Escape')
  await page.reload()
  await page.locator('.diff-table tr.added').first().waitFor()
  await page.locator('.changes-view').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/live-file-diff-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(()=>document.getElementById('sidebar').getBoundingClientRect().right<=0)
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Production file diff must fit mobile')
  await page.screenshot({path:'artifacts/live-file-diff-mobile.png',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(base + "/?demo=1")
  await page.getByRole("heading", {name:"v2 meets v1"}).waitFor()
  for (const [number, heading] of [[1,"Good things take shape."],[2,"A little more space to create."]]) {
    await page.frameLocator(`iframe[title="Preview of v${number}"]`).getByRole("heading", {name:heading}).waitFor()
  }
  await page.getByText("Live demo rendered and verified.", {exact:false}).first().waitFor()
  check(await page.getByRole("button", {name:"Restore version",exact:true}).isDisabled(), "Shared demo must be read only")
  const grip = page.getByRole("button", {name:"Resize preview of v2",exact:true})
  await grip.focus()
  await page.keyboard.press("Shift+ArrowLeft")
  check(await page.locator('iframe[title="Preview of v2"]').evaluate(e=>e.style.width === "1180px"), "Production viewport must resize")
  await page.getByRole("button",{name:"Reset preview size for v2",exact:true}).click()
  await page.locator("iframe").first().scrollIntoViewIfNeeded()
  await page.screenshot({path:"artifacts/live-demo-comparison.png"})
  await page.screenshot({path:"artifacts/live-demo-full.png",fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(() => document.getElementById('sidebar').getBoundingClientRect().right <= 0)
  check(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), "Production demo must fit a mobile screen")
  await page.locator('main h1').click()
  await page.locator("iframe").first().scrollIntoViewIfNeeded()
  await page.screenshot({path:"artifacts/live-demo-mobile.png",fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(base)
  await page.getByRole("button",{name:"Connect Spacefast",exact:true}).first().click()
  check(!(await page.getByRole("checkbox",{name:/Allow restoring/}).isChecked()), "Fresh connection must default to read only")
  await page.getByRole("button",{name:"Continue to Spacefast",exact:true}).click()
  await page.waitForURL(url=>url.origin === "https://my.spacefast.com", {timeout:15000})
  await page.getByRole("heading",{name:"Sign in or sign up",exact:true}).waitFor()
  await page.screenshot({path:"artifacts/live-oauth-entry.png"})
  return ["Public runtime, database, real comparison frames, resize, file diffs, exact share links, reload, mobile layout, deployed security headers and fresh-browser OAuth navigation passed", "No personal account was signed in and no deployment was restored by this test"]
}
