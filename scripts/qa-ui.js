async (page) => {
  const base = new URL(page.url()).origin
  const check = (value, message) => { if (!value) throw new Error(message) }
  const results = []
  const audit = async (name) => {
    await page.addScriptTag({ path: "node_modules/axe-core/axe.min.js" })
    const violations = await page.evaluate(async () => (await axe.run(document, { runOnly: ["wcag2a", "wcag2aa", "wcag21aa"] })).violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })))
    check(!violations.length, `${name}: ${JSON.stringify(violations)}`)
    results.push(`${name}: zero automated WCAG AA violations`)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  await page.getByRole("heading", { name: "Your next chapter starts with a look back." }).waitFor()
  await audit("Welcome")
  await page.getByRole("button", { name: "Connect Spacefast", exact: true }).first().click()
  await page.getByRole("dialog", { name: "Connect your Spacefast" }).waitFor()
  check(!(await page.getByRole("checkbox", { name: /Allow restoring/ }).isChecked()), "Connection must start read only")
  await audit("Connection dialog")
  let signInOrigin
  await page.route("**/api/auth/start", async route => {
    signInOrigin = route.request().headers().origin
    await route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:"Sign-in request checked."})})
  })
  await page.getByRole("button", { name: "Continue to Spacefast", exact: true }).click()
  await page.getByText("Sign-in request checked.", {exact:true}).waitFor()
  check(signInOrigin === base, "The real browser sign-in form must send its same-origin Origin header")
  await page.unroute("**/api/auth/start")
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Try live demo", exact: true }).click()
  await page.getByRole("heading", { name: "v2 meets v1" }).waitFor()
  check(await page.getByRole("button", { name: "Restore version", exact: true }).isDisabled(), "Public demo must never restore")
  await page.frameLocator('iframe[title="Preview of v2"]').getByRole("heading", { name: "A little more space to create." }).waitFor()
  await page.frameLocator('iframe[title="Preview of v1"]').getByRole("heading", { name: "Good things take shape." }).waitFor()
  await page.getByText("Live demo rendered and verified.", { exact: false }).first().waitFor()
  check((await page.getByText("Live demo rendered and verified.", { exact: false }).count()) === 2, "Both controlled real deployments must signal readiness")
  await page.locator("iframe").first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: "artifacts/demo-comparison.png" })
  await page.screenshot({ path: "artifacts/demo-desktop-full.png", fullPage: true })
  await audit("Real public demo")
  await page.getByRole("combobox", { name: "Filter versions by status" }).selectOption("failed")
  await page.getByText("No versions match this filter.", { exact: true }).waitFor()
  await page.getByRole("combobox", { name: "Filter versions by status" }).selectOption("all")
  await page.getByRole("textbox", { name: "Search version history" }).fill("Terra")
  check((await page.locator(".version-item").count()) === 1, "Search must filter actual version metadata")
  await page.locator(".version-item").click()
  await page.getByRole("heading", { name: "v1 meets v2" }).waitFor()
  const grip = page.getByRole("button", { name: "Resize preview of v1", exact: true })
  await grip.focus()
  await page.keyboard.press("ArrowRight")
  check(await page.locator('iframe[title="Preview of v1"]').evaluate(el => el.style.width === "1290px"), "Keyboard resizing must change the real iframe viewport")
  const handle = await grip.boundingBox()
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2 - 25, handle.y + handle.height / 2 + 15, { steps: 5 })
  await page.mouse.up()
  check(await page.locator('iframe[title="Preview of v1"]').evaluate(el => parseInt(el.style.width) < 1290 && parseInt(el.style.height) > 900), "Pointer drag must resize width and height")
  await page.getByRole("button", { name: "Reset preview size for v1", exact: true }).click()
  check(await page.locator('iframe[title="Preview of v1"]').evaluate(el => el.style.width === "1280px" && el.style.height === "900px"), "Reset must restore desktop viewport")
  await page.getByRole("textbox", { name: "Search version history" }).fill("")
  await page.getByRole("tab", { name: "Details", exact: true }).click()
  await page.getByText("Unavailable · direct upload or no provenance", { exact: true }).waitFor()
  await audit("Version details")
  await page.getByRole("tab", { name: "Compare", exact: true }).click()
  await page.getByRole("button", { name: "Mobile preview", exact: true }).click()
  check((await page.locator(".mobile-frame").count()) === 2, "Mobile preview affects both frames")
  await page.getByRole("button", { name: "Built with honest limits", exact: true }).click()
  await audit("Capabilities dialog")
  await page.keyboard.press("Escape")
  await page.reload()
  await page.getByRole("heading", { name: "v1 meets v2" }).waitFor()
  check(new URL(page.url()).searchParams.get("version") === "ver_ed7fee22bb1842d3badda9f627fbfffe", "Selected comparison must survive reload")
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "No horizontal overflow on mobile")
  await page.getByRole("button", { name: "Toggle navigation" }).click()
  await page.getByRole("link", { name: "Spacefast Time Machine home" }).waitFor({state:"visible"})
  await page.keyboard.press("Escape")
  await page.locator("iframe").first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: "artifacts/demo-mobile.png", fullPage: true })
  await audit("Mobile demo")
  await page.goto(base)
  await page.getByRole("heading", { name: "Your next chapter starts with a look back." }).waitFor()
  await audit("Mobile welcome")
  await page.screenshot({ path: "artifacts/welcome-mobile.png", fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  return [...results, "Real deployed frame content, readiness signals, filters, search, version selection, metadata, navigation, demo reload and responsive layout passed"]
}
